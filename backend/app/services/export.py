"""Markdown and BibTeX export (SRS FR-40, FR-41), built from validated data only (R-4)."""

from __future__ import annotations

import re
import unicodedata

from app.models.schemas import Paper, ReviewResult


def _cell(text: str) -> str:
    """Make text safe inside a Markdown table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def _authors_short(authors: list[str]) -> str:
    if not authors:
        return "Unknown"
    if len(authors) <= 3:
        return ", ".join(authors)
    return f"{authors[0]} et al."


def to_markdown(r: ReviewResult) -> str:
    lines = [f"# Literature review: {r.topic}", ""]
    lines.append(
        f"_Generated by LitLens on {r.created_at:%Y-%m-%d} from {len(r.papers)} arXiv papers._"
    )
    lines.append("")
    if r.review_md:
        lines += [r.review_md.strip(), ""]
    else:
        lines += ["_The review text could not be generated for this run._", ""]

    if r.extractions:
        by_ref = {p.ref: p for p in r.papers}
        lines += [
            "## Comparison table",
            "",
            "| Ref | Title | Method | Dataset(s) | Key result | Limitations |",
            "|---|---|---|---|---|---|",
        ]
        for e in r.extractions:
            p = by_ref.get(e.ref)
            lines.append(
                f"| [{e.ref}] | {_cell(p.title if p else '')} | {_cell(e.method)} | "
                f"{_cell(', '.join(e.datasets) or 'Not reported')} | "
                f"{_cell(e.key_result)} | {_cell(e.limitations)} |"
            )
        lines.append("")

    lines += ["## References", ""]
    for p in r.papers:
        lines.append(
            f"[{p.ref}] {_authors_short(p.authors)} ({p.year}). {p.title}. "
            f"arXiv:{p.arxiv_id}. {p.url_abs}"
        )
    lines.append("")
    return "\n".join(lines)


def bibtex_escape(text: str) -> str:
    """Escape BibTeX/LaTeX specials; braces and backslashes can't break the entry."""
    out = []
    for ch in " ".join(text.split()):
        if ch == "\\":
            out.append(r"\textbackslash{}")
        elif ch in "{}":
            out.append("\\" + ch)
        elif ch in "&%$#_":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def _ascii_word(text: str) -> str:
    norm = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^A-Za-z0-9]", "", norm)


def bibtex_key(p: Paper, used: set[str]) -> str:
    surname = _ascii_word(p.authors[0].split()[-1]) if p.authors else "anon"
    first_word = next(
        (w for w in (_ascii_word(w) for w in p.title.split()) if len(w) > 3), "paper"
    )
    base = f"{surname.lower() or 'anon'}{p.year}{first_word.lower()}"
    key, n = base, 1
    while key in used:
        n += 1
        key = f"{base}{n}"
    used.add(key)
    return key


def to_bibtex(papers: list[Paper]) -> str:
    used: set[str] = set()
    entries = []
    for p in papers:
        fields = {
            "title": "{" + bibtex_escape(p.title) + "}",  # double braces keep capitals
            "author": " and ".join(bibtex_escape(a) for a in p.authors) or "Unknown",
            "year": str(p.year),
            "eprint": p.arxiv_id,
            "archivePrefix": "arXiv",
            "primaryClass": bibtex_escape(p.primary_category),
            "url": p.url_abs,
        }
        body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields.items())
        entries.append(f"@misc{{{bibtex_key(p, used)},\n{body}\n}}")
    return "\n\n".join(entries) + "\n"
